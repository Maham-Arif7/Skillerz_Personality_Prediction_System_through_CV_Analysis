"""
report.py
------------------------------------------------------------------
Generates a downloadable one-page PDF report summarizing a
candidate's personality prediction results.
"""

from datetime import date

from fpdf import FPDF

TRAIT_ORDER = ["Openness", "Conscientiousness", "Extraversion", "Agreeableness", "Emotional Stability"]


class _ReportPDF(FPDF):
    def header(self):
        self.set_fill_color(20, 20, 45)
        self.rect(0, 0, 210, 28, "F")
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 16)
        self.set_xy(10, 8)
        self.cell(0, 8, "Personality Prediction Report", ln=1)
        self.set_font("Helvetica", "", 10)
        self.set_xy(10, 17)
        self.cell(0, 6, "CV Analysis - Generated by Personality Prediction System", ln=1)
        self.ln(8)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, f"Generated on {date.today().isoformat()}  |  Page {self.page_no()}", align="C")


def build_pdf_report(candidate_name: str, contact: dict, result: dict) -> bytes:
    pdf = _ReportPDF()
    pdf.add_page()
    pdf.set_text_color(20, 20, 20)

    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 8, f"Candidate: {candidate_name}", ln=1)
    pdf.set_font("Helvetica", "", 10)
    contact_line = "  |  ".join(filter(None, [contact.get("email"), contact.get("phone")]))
    if contact_line:
        pdf.cell(0, 6, contact_line, ln=1)
    pdf.ln(4)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Big Five (OCEAN) Trait Scores", ln=1)
    pdf.set_font("Helvetica", "", 10)

    scores = result["scores"]
    for trait in TRAIT_ORDER:
        val = scores.get(trait, 0)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(60, 7, trait, border=0)
        pdf.set_font("Helvetica", "", 10)
        bar_width = 100
        filled = bar_width * (val / 100)
        x, y = pdf.get_x(), pdf.get_y()
        pdf.set_fill_color(230, 230, 230)
        pdf.rect(x, y + 1, bar_width, 4, "F")
        pdf.set_fill_color(90, 110, 210)
        pdf.rect(x, y + 1, filled, 4, "F")
        pdf.set_xy(x + bar_width + 4, y)
        pdf.cell(20, 7, f"{val:.0f}/100", ln=1)

    pdf.set_x(pdf.l_margin)
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Suggested Role Fit", ln=1)
    pdf.set_font("Helvetica", "", 10)
    for fit in result.get("role_fit", []):
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(0, 6, f"- {fit['category']} (match {fit['match_score']:.0f}/100): {', '.join(fit['roles'])}")

    pdf.set_x(pdf.l_margin)
    pdf.ln(2)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Top Resume Keywords", ln=1)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(0, 6, ", ".join(result.get("top_keywords", [])) or "N/A")

    pdf.set_x(pdf.l_margin)
    pdf.ln(2)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(120, 120, 120)
    pdf.multi_cell(
        0, 5,
        "Disclaimer: This report is generated using an automated NLP/lexicon-based analysis of resume "
        "language for informational and educational purposes. It is not a validated psychometric "
        "assessment and should not be the sole basis for hiring decisions."
    )

    return bytes(pdf.output(dest="S"))
